# Practicar For Loops en Python
#imprimir los numero del 1-10 con un for
# range se usa para generar una secuencia de números
for counter in range(1, 11):
    print(counter)
    
# imprimir la tabla de multiplicar del 5
NUMBER = 5
for i in range(1, 11):
    result = NUMBER * i
    print(f"{NUMBER} x {i} = {result}")